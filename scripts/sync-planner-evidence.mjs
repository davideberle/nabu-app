#!/usr/bin/env node
// Mirror + parity check for the Kitchen-owned reviewed planner evidence ledger
// (Kitchen DESIGN.md §4.1 "Reviewed planner evidence").
//
// Canonical file lives in the workspace:
//   $KITCHEN_PLANNER_EVIDENCE_DIR/reviewed-planner-evidence.json
//   (default ~/.openclaw/workspace/projects/kitchen/planner-evidence)
// The deployable mirror lives in this repo under src/data/kitchen/:
//   reviewed-planner-evidence.json          verbatim copy of the ledger
//   reviewed-planner-evidence.generated.ts  the module the runtime imports
//   manifest.json                           SHA-256 of every mirrored file
// and the RULE itself (Kitchen-owned code) is projected verbatim to
//   src/lib/kitchen/planner-evidence-rule.ts
//
//   node scripts/sync-planner-evidence.mjs          # copy canonical → mirror, regenerate, write manifest
//   node scripts/sync-planner-evidence.mjs --check  # verify mirror == manifest and generated == f(copy);
//                                                   # when the canonical dir exists, canonical == mirror
//
// `--check` runs in `prebuild`. On Vercel the canonical dir is absent, so only
// the mirror/manifest integrity is verified there; locally both halves are.

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const mirrorDir = resolve(here, "..", "src", "data", "kitchen");
const ruleMirrorDir = resolve(here, "..", "src", "lib", "kitchen");
const FILE = "reviewed-planner-evidence.json";
const GENERATED = "reviewed-planner-evidence.generated.ts";
const RULE = "planner-evidence-rule.ts";
// Two further Kitchen-owned evidence files are mirrored the same way (Kitchen
// DESIGN.md §4.3.1): the cited Swiss monthly produce calendar and the frozen
// Jev v2 taxonomy rubric the weekly content review is bound to.
const EXTRA = [
  { file: "swiss-season-calendar.json", generated: "swiss-season-calendar.generated.ts", symbol: "SWISS_SEASON_CALENDAR", consumer: "src/lib/planner-seasonality.ts" },
  { file: "jev-taxonomy-rubric-v2.json", generated: "jev-taxonomy-rubric-v2.generated.ts", symbol: "JEV_TAXONOMY_RUBRIC", consumer: "src/lib/planner-review.ts" },
];
const manifestPath = join(mirrorDir, "manifest.json");
const canonicalDir =
  process.env.KITCHEN_PLANNER_EVIDENCE_DIR ||
  join(homedir(), ".openclaw", "workspace", "projects", "kitchen", "planner-evidence");

function sha256(buffer) {
  return createHash("sha256").update(buffer).digest("hex");
}

function fail(message) {
  console.error(`sync-planner-evidence: ${message}`);
  process.exit(1);
}

/** Verbatim JSON → TypeScript module. The runtime validates the shape itself. */
function renderModule(jsonText) {
  const parsed = JSON.parse(jsonText); // fail loudly on a malformed canonical file
  return (
    "// GENERATED by scripts/sync-planner-evidence.mjs from the Kitchen-owned\n" +
    "// reviewed-planner-evidence.json — do not edit. Validated at load by\n" +
    "// src/lib/planner-evidence.ts and at build by scripts/check-planner-evidence.mjs.\n" +
    "export const REVIEWED_PLANNER_EVIDENCE: unknown = " +
    JSON.stringify(parsed, null, 2) +
    ";\n"
  );
}

function renderExtraModule(extra, jsonText) {
  const parsed = JSON.parse(jsonText);
  return (
    `// GENERATED by scripts/sync-planner-evidence.mjs from the Kitchen-owned\n` +
    `// ${extra.file} — do not edit. Validated at load by ${extra.consumer}.\n` +
    `export const ${extra.symbol}: unknown = ` +
    JSON.stringify(parsed, null, 2) +
    ";\n"
  );
}

const check = process.argv.includes("--check");

if (!check) {
  const source = join(canonicalDir, FILE);
  if (!existsSync(source)) fail(`canonical file not found: ${source}`);
  const bytes = readFileSync(source);
  mkdirSync(mirrorDir, { recursive: true });
  writeFileSync(join(mirrorDir, FILE), bytes);
  const generated = renderModule(bytes.toString("utf8"));
  writeFileSync(join(mirrorDir, GENERATED), generated);
  const ruleSource = join(canonicalDir, RULE);
  if (!existsSync(ruleSource)) fail(`canonical rule not found: ${ruleSource}`);
  const rule = readFileSync(ruleSource);
  mkdirSync(ruleMirrorDir, { recursive: true });
  writeFileSync(join(ruleMirrorDir, RULE), rule);
  const manifest = {
    source: "projects/kitchen/planner-evidence/",
    files: { [FILE]: sha256(bytes), [GENERATED]: sha256(generated), ["../../lib/kitchen/" + RULE]: sha256(rule) },
  };
  for (const extra of EXTRA) {
    const extraSource = join(canonicalDir, extra.file);
    if (!existsSync(extraSource)) fail(`canonical file not found: ${extraSource}`);
    const extraBytes = readFileSync(extraSource);
    writeFileSync(join(mirrorDir, extra.file), extraBytes);
    const extraGenerated = renderExtraModule(extra, extraBytes.toString("utf8"));
    writeFileSync(join(mirrorDir, extra.generated), extraGenerated);
    manifest.files[extra.file] = sha256(extraBytes);
    manifest.files[extra.generated] = sha256(extraGenerated);
  }
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
  console.log(`sync-planner-evidence: mirrored ${FILE} (${manifest.files[FILE].slice(0, 12)}…) and regenerated ${GENERATED}`);
  process.exit(0);
}

if (!existsSync(manifestPath)) fail(`mirror manifest missing: ${manifestPath}`);
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
const problems = [];
for (const name of [FILE, GENERATED, "../../lib/kitchen/" + RULE, ...EXTRA.flatMap((extra) => [extra.file, extra.generated])]) {
  const path = join(mirrorDir, name);
  if (!existsSync(path)) {
    problems.push(`mirror file missing: ${name}`);
    continue;
  }
  const actual = sha256(readFileSync(path));
  if (manifest.files?.[name] !== actual) problems.push(`mirror drift: ${name} (manifest ${manifest.files?.[name]}, actual ${actual})`);
}
const copyPath = join(mirrorDir, FILE);
if (existsSync(copyPath) && existsSync(join(mirrorDir, GENERATED))) {
  const expected = renderModule(readFileSync(copyPath, "utf8"));
  if (readFileSync(join(mirrorDir, GENERATED), "utf8") !== expected) {
    problems.push(`${GENERATED} is not the module generated from ${FILE}`);
  }
}
for (const extra of EXTRA) {
  const copy = join(mirrorDir, extra.file);
  const generated = join(mirrorDir, extra.generated);
  if (existsSync(copy) && existsSync(generated) && readFileSync(generated, "utf8") !== renderExtraModule(extra, readFileSync(copy, "utf8"))) {
    problems.push(`${extra.generated} is not the module generated from ${extra.file}`);
  }
}
if (existsSync(canonicalDir)) {
  for (const extra of EXTRA) {
    const extraSource = join(canonicalDir, extra.file);
    if (!existsSync(extraSource)) problems.push(`canonical dir present but ${extra.file} missing: ${extraSource}`);
    else if (sha256(readFileSync(extraSource)) !== sha256(readFileSync(join(mirrorDir, extra.file)))) {
      problems.push(`canonical ${extra.file} differs from the mirror — run node scripts/sync-planner-evidence.mjs`);
    }
  }
  const source = join(canonicalDir, FILE);
  if (!existsSync(source)) {
    problems.push(`canonical dir present but ${FILE} missing: ${source}`);
  } else if (sha256(readFileSync(source)) !== sha256(readFileSync(copyPath))) {
    problems.push(`canonical ${FILE} differs from the mirror — run node scripts/sync-planner-evidence.mjs`);
  }
  const ruleSource = join(canonicalDir, RULE);
  if (!existsSync(ruleSource)) problems.push(`canonical rule missing: ${ruleSource}`);
  else if (sha256(readFileSync(ruleSource)) !== sha256(readFileSync(join(ruleMirrorDir, RULE)))) {
    problems.push(`canonical ${RULE} differs from the app projection src/lib/kitchen/${RULE} — edit the Kitchen rule and run node scripts/sync-planner-evidence.mjs`);
  }
} else {
  console.log(`sync-planner-evidence: canonical dir not present (${canonicalDir}); verified mirror integrity only.`);
}
if (problems.length) {
  for (const problem of problems) console.error(`sync-planner-evidence: ${problem}`);
  process.exit(1);
}
console.log("sync-planner-evidence: mirror matches manifest" + (existsSync(canonicalDir) ? " and canonical." : "."));
