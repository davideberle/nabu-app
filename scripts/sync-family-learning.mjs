#!/usr/bin/env node
// Mirror + parity check for the Family Assistant-owned learning content and
// schema (family-assistant/learning/CONTRACT.md).
//
// Canonical files live in the workspace:
//   $FAMILY_LEARNING_CANONICAL_DIR (default
//   ~/.openclaw/workspace/projects/family-assistant/learning)
// The deployable copy lives in this repo under src/data/family-learning/ with a
// manifest of SHA-256 hashes.
//
//   node scripts/sync-family-learning.mjs          # copy canonical → mirror, write manifest
//   node scripts/sync-family-learning.mjs --check  # verify mirror == manifest; and, when the
//                                                  # canonical dir exists, canonical == mirror
//
// `--check` runs in `prebuild`. On Vercel the canonical dir is absent, so only
// the mirror/manifest integrity is verified there; locally both halves are.

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const mirrorDir = resolve(here, "..", "src", "data", "family-learning");
const manifestPath = join(mirrorDir, "manifest.json");
const canonicalDir =
  process.env.FAMILY_LEARNING_CANONICAL_DIR ||
  join(homedir(), ".openclaw", "workspace", "projects", "family-assistant", "learning");

/** Files mirrored verbatim, relative to both directories. */
function listCanonicalFiles(dir) {
  const files = ["schema.sql"];
  const contentDir = join(dir, "content");
  if (existsSync(contentDir)) {
    for (const name of readdirSync(contentDir).sort()) {
      if (name.endsWith(".json")) files.push(`content/${name}`);
    }
  }
  return files;
}

/**
 * schema.sql → schema.generated.ts. Next.js cannot import a raw .sql file, so
 * the runtime guard reads this derived module; `--check` regenerates it in
 * memory and fails on any difference, keeping schema.sql the single source.
 */
function renderSchemaModule(sql) {
  const statements = sql
    .split(/^;;\s*$/m)
    .map((chunk) => chunk.replace(/^\s*--.*$/gm, "").trim())
    .filter(Boolean);
  return (
    "// GENERATED by scripts/sync-family-learning.mjs from schema.sql — do not edit.\n" +
    "export const FAMILY_LEARNING_SCHEMA_STATEMENTS: readonly string[] = [\n" +
    statements.map((stmt) => `  ${JSON.stringify(stmt)},`).join("\n") +
    "\n];\n"
  );
}

function sha256(buffer) {
  return createHash("sha256").update(buffer).digest("hex");
}

function fail(message) {
  console.error(`sync-family-learning: ${message}`);
  process.exit(1);
}

const check = process.argv.includes("--check");

if (!check) {
  if (!existsSync(canonicalDir)) fail(`canonical dir not found: ${canonicalDir}`);
  const files = listCanonicalFiles(canonicalDir);
  const manifest = { source: "projects/family-assistant/learning", files: {} };
  for (const rel of files) {
    const bytes = readFileSync(join(canonicalDir, rel));
    const target = join(mirrorDir, rel);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, bytes);
    manifest.files[rel] = { sha256: sha256(bytes), bytes: bytes.length };
  }
  writeFileSync(join(mirrorDir, "schema.generated.ts"), renderSchemaModule(readFileSync(join(canonicalDir, "schema.sql"), "utf8")));
  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`sync-family-learning: mirrored ${files.length} file(s) → ${mirrorDir}`);
  process.exit(0);
}

if (!existsSync(manifestPath)) fail(`manifest missing: ${manifestPath}`);
const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
const names = Object.keys(manifest.files ?? {});
if (names.length === 0) fail("manifest lists no files");

const problems = [];
for (const rel of names) {
  const target = join(mirrorDir, rel);
  if (!existsSync(target)) {
    problems.push(`mirror file missing: ${rel}`);
    continue;
  }
  const digest = sha256(readFileSync(target));
  if (digest !== manifest.files[rel].sha256) problems.push(`mirror drift: ${rel}`);
}

{
  const generatedPath = join(mirrorDir, "schema.generated.ts");
  const schemaPath = join(mirrorDir, "schema.sql");
  if (!existsSync(generatedPath) || !existsSync(schemaPath)) problems.push("schema.generated.ts or schema.sql missing");
  else if (readFileSync(generatedPath, "utf8") !== renderSchemaModule(readFileSync(schemaPath, "utf8"))) problems.push("schema.generated.ts is stale (run without --check)");
}

if (existsSync(canonicalDir)) {
  const canonicalFiles = listCanonicalFiles(canonicalDir);
  for (const rel of canonicalFiles) {
    if (!names.includes(rel)) problems.push(`canonical file not mirrored: ${rel}`);
  }
  for (const rel of names) {
    const source = join(canonicalDir, rel);
    if (!existsSync(source)) {
      problems.push(`mirrored file no longer canonical: ${rel}`);
      continue;
    }
    if (sha256(readFileSync(source)) !== manifest.files[rel].sha256) {
      problems.push(`canonical differs from mirror: ${rel} (run without --check to re-sync)`);
    }
  }
}

if (problems.length > 0) {
  for (const problem of problems) console.error(`sync-family-learning: ${problem}`);
  process.exit(1);
}
console.log(
  `sync-family-learning: ${names.length} file(s) verified` +
    (existsSync(canonicalDir) ? " (mirror + canonical parity)" : " (mirror integrity; canonical dir absent)"),
);
