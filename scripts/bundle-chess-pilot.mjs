#!/usr/bin/env node
// Embeds the Game Studio-owned Adaptive Chess Coach pilot bundle for gated delivery (October 8, 2026).
//
// Source (one-way projection from projects/game-studio/games/adaptive-chess-coach via ops/sync-chess-pilot.sh):
//   src/games/adaptive-chess-coach/{index.html,chess-ai.js,chess-coach.js,chess-engine.js,chess-ui.js}
// Output (committed, deploy mirror; Vercel cannot read files at request time reliably):
//   src/data/adaptive-chess-coach/bundle.generated.ts  — the five files as strings
//   src/data/adaptive-chess-coach/manifest.json        — SHA-256 per source file
//
//   node scripts/bundle-chess-pilot.mjs          # regenerate module + manifest from the sources
//   node scripts/bundle-chess-pilot.mjs --check  # verify sources == manifest and module == regeneration (prebuild)
//
// Nothing under public/ serves these files any more: the only runnable form is the credential-gated
// route /games/adaptive-chess-coach/index.html, which inlines the scripts into one document.

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const sourceDir = resolve(here, "..", "src", "games", "adaptive-chess-coach");
const outDir = resolve(here, "..", "src", "data", "adaptive-chess-coach");
const modulePath = join(outDir, "bundle.generated.ts");
const manifestPath = join(outDir, "manifest.json");
export const CHESS_BUNDLE_FILES = ["index.html", "chess-engine.js", "chess-ai.js", "chess-coach.js", "chess-ui.js"];

const sha256 = (text) => createHash("sha256").update(text).digest("hex");

function readSources() {
  const files = {};
  for (const name of CHESS_BUNDLE_FILES) {
    const file = join(sourceDir, name);
    if (!existsSync(file)) throw new Error(`chess bundle source missing: ${file}`);
    files[name] = readFileSync(file, "utf8");
  }
  return files;
}

function renderModule(files) {
  return (
    "// GENERATED by scripts/bundle-chess-pilot.mjs from src/games/adaptive-chess-coach — do not edit.\n" +
    "// The Game Studio-owned pilot bundle, embedded so the gated route can serve it without touching the filesystem.\n" +
    "export const ADAPTIVE_CHESS_COACH_BUNDLE: Readonly<Record<string, string>> = Object.freeze({\n" +
    CHESS_BUNDLE_FILES.map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(files[name])},`).join("\n") +
    "\n});\n"
  );
}

function renderManifest(files) {
  return JSON.stringify({ generatedBy: "scripts/bundle-chess-pilot.mjs", files: Object.fromEntries(CHESS_BUNDLE_FILES.map((name) => [name, { sha256: sha256(files[name]), bytes: Buffer.byteLength(files[name]) }])) }, null, 2) + "\n";
}

const check = process.argv.includes("--check");
const files = readSources();
const module_ = renderModule(files);
const manifest = renderManifest(files);
if (check) {
  const problems = [];
  if (!existsSync(modulePath) || readFileSync(modulePath, "utf8") !== module_) problems.push("bundle.generated.ts differs from the sources");
  if (!existsSync(manifestPath) || readFileSync(manifestPath, "utf8") !== manifest) problems.push("manifest.json differs from the sources");
  if (existsSync(resolve(here, "..", "public", "games", "adaptive-chess-coach"))) problems.push("public/games/adaptive-chess-coach must not exist (the bundle is gated, not static)");
  if (problems.length) {
    console.error(`✗ chess bundle parity: ${problems.join("; ")} — run node scripts/bundle-chess-pilot.mjs`);
    process.exit(1);
  }
  console.log(`✓ chess bundle parity: ${CHESS_BUNDLE_FILES.length} files embedded and hashed`);
} else {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(modulePath, module_);
  writeFileSync(manifestPath, manifest);
  console.log(`✓ wrote ${modulePath} and ${manifestPath}`);
}
