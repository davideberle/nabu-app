#!/usr/bin/env node
// Regenerates src/data/family-learning/island-plates.json (ids + sha256 — evidence) and the static-import module
// src/components/family/learning/harbor-island-plate-assets.ts from the PNG plates present under src/assets/family-learning/island/.
// Plate file names are the plate ids (see harbor-island-plates.ts PLATE_BOXES): backdrop.png, workshop.png, keeper.png …
// Only known ids are listed; anything else is ignored with a note. No image is modified. Plates are build-time static assets
// (Next.js static image imports → /_next/static/media/<name>.<hash>.png, outside the auth middleware), never public/ files
// (continuation 2026-10-11: the local auth gate redirected a child session away from a public/ plate).
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "src/assets/family-learning/island");
const out = path.join(root, "src/data/family-learning/island-plates.json");
const mod = path.join(root, "src/components/family/learning/harbor-island-plate-assets.ts");
const KNOWN = ["crate","boat-hull","boat-sail","pier-module","pier-head","plank-pile","garden-bed","seedling","station-bed","supply-store","logbook-stand","wordbook-stand","marker-turtle","marker-waves","overlay-forest","overlay-crater","overlay-ice","sky", "sea", "backdrop", "far-mainland", "far-lighthouse", "far-ship", "workshop", "office", "shop", "harbormaster", "keeper", "planner", "supplier", "child", "tent", "hut", "station", "pier"];
const files = existsSync(dir) ? readdirSync(dir).filter((f) => /\.(png|webp)$/i.test(f)).sort() : [];
const plates = [];
for (const f of files) {
  const id = f.replace(/\.(png|webp)$/i, "");
  if (!KNOWN.includes(id)) { console.log(`ignored (unknown plate id): ${f}`); continue; }
  const sha256 = createHash("sha256").update(readFileSync(path.join(dir, f))).digest("hex");
  plates.push({ id, file: `src/assets/family-learning/island/${f}`, sha256 });
}
const current = JSON.parse(readFileSync(out, "utf8"));
const note = "Painted plates for the Visit 5 island (owned scene layers). Regenerate with `node scripts/island-plates.mjs` after dropping PNGs into src/assets/family-learning/island/ (build-time static assets, outside the auth gate). Empty = the vector scene draws everything. Live state (crates, boats, ropes, flags, badges, labels, avatar) is never part of a plate.";
writeFileSync(out, JSON.stringify({ note: current.note?.includes("src/assets") ? current.note : note, plates }, null, 2) + "\n");
const ident = (id) => id.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const lines = [
  "// GENERATED by scripts/island-plates.mjs from the PNGs under src/assets/family-learning/island/ — do not edit.",
  "// Static image imports: Next.js emits each plate under /_next/static/media/<name>.<hash>.png (content-hashed, immutable,",
  "// served outside the auth middleware — identical locally and on Vercel). A plate not present here leaves the vector drawing.",
  'import type { StaticImageData } from "next/image";',
  ...plates.map((p) => `import ${ident(p.id)} from "@/assets/family-learning/island/${path.basename(p.file)}";`),
  "",
  "export const PLATE_ASSETS: Readonly<Record<string, StaticImageData>> = {",
  ...plates.map((p) => `  "${p.id}": ${ident(p.id)},`),
  "};",
  "",
];
writeFileSync(mod, lines.join("\n"));
console.log(`island-plates: ${plates.length} plate(s) listed → ${path.relative(root, out)}, ${path.relative(root, mod)}`);
